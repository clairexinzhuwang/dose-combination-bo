"""Independent path core for the frozen budget/toxicity-calibration audit.

The audit deliberately does not edit :mod:`dose_combination_bo.trial`.  Instead, one
process-local call temporarily injects a fixed-noise fitting shim and an audited
``Context`` constructor into the already frozen trial harness.  The shim changes
only the toxicity likelihood variance used for fitting; observations continue to
be generated by the frozen harness at the OSA truth noise.  Every injected global
is restored in ``finally``.

One maximum-budget path is generated and its shorter terminal states are replayed
from exact allocation/observation prefixes.  The replay serializes enough
posterior state that downstream analysis never needs to refit a GP.
"""
